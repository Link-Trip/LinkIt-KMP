#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const specsDir = path.resolve('docs/specs');
const featureListPath = path.join(specsDir, 'feature-list.json');
const trackingPath = path.join(specsDir, 'feature-tracking.json');
const trackingJsPath = path.join(specsDir, 'feature-tracking.js');
const eventsPath = path.join(specsDir, 'feature-events.jsonl');

const trackingSchemaVersion = 'spec-command-center.feature-tracking.v1';
const eventSchemaVersion = 'spec-command-center.feature-events.v1';

const workStatuses = ['not_started', 'in_progress', 'in_review', 'implemented', 'verified', 'blocked', 'deferred'];
const checkStatuses = ['not_started', 'passed', 'failed', 'not_applicable'];
const planStatuses = ['empty', 'draft', 'ready', 'in_progress', 'done'];
const agents = ['codex', 'claude'];

function readJson(filePath, fallback) {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function parseArgs(argv) {
  const args = { _: [] };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith('--')) {
      args._.push(token);
      continue;
    }

    const key = token.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith('--')) {
      args[key] = true;
      continue;
    }

    args[key] = next;
    index += 1;
  }
  return args;
}

function currentBranch() {
  try {
    return execSync('git branch --show-current', { encoding: 'utf8' }).trim() || null;
  } catch {
    return null;
  }
}

function defaultActor() {
  return process.env.USER || process.env.LOGNAME || 'unknown';
}

function currentGitHubLogin() {
  try {
    const login = execSync('gh api user --jq .login', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (login) return login;
  } catch {
    // Fall back to local git config below when gh is not authenticated.
  }

  try {
    const email = execSync('git config user.email', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    const match = email.match(/\+([^@]+)@users\.noreply\.github\.com$/);
    if (match?.[1]) return match[1];
  } catch {
    // Fall through to user.name.
  }

  try {
    const name = execSync('git config user.name', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (name) return name;
  } catch {
    // Fall through to shell user.
  }

  return defaultActor();
}

function defaultEntry(featureUid) {
  return {
    featureUid,
    workStatus: 'not_started',
    developer: 'Unassigned',
    issue: null,
    pr: null,
    branch: null,
    testStatus: 'not_started',
    screenshotStatus: 'not_started',
    blockedReason: null,
    notes: '',
    workPlan: {
      status: 'empty',
      summary: '',
      tasks: [],
      affectedFiles: [],
      testPlan: [],
      risks: [],
      updatedAt: null,
      updatedBy: null,
    },
    promptHistory: [],
    updatedAt: null,
    updatedBy: null,
  };
}

function defaultActiveWork() {
  return Object.fromEntries(agents.map((agent) => [agent, null]));
}

function loadFeatureList() {
  if (!fs.existsSync(featureListPath)) {
    throw new Error(`Missing feature list: ${featureListPath}`);
  }
  return readJson(featureListPath);
}

function loadTracking(featureList) {
  const tracking = readJson(trackingPath, {
    schemaVersion: trackingSchemaVersion,
    updatedAt: null,
    activeWork: defaultActiveWork(),
    features: {},
  });

  tracking.schemaVersion = tracking.schemaVersion || trackingSchemaVersion;
  tracking.activeWork = {
    ...defaultActiveWork(),
    ...(tracking.activeWork || {}),
  };
  tracking.features = tracking.features || {};

  const validUids = new Set(featureList.features.map((feature) => feature.uid));
  for (const feature of featureList.features) {
    tracking.features[feature.uid] = {
      ...defaultEntry(feature.uid),
      ...tracking.features[feature.uid],
      featureUid: feature.uid,
    };
  }

  for (const uid of Object.keys(tracking.features)) {
    if (!validUids.has(uid)) {
      tracking.features[uid].orphaned = true;
    }
  }

  return tracking;
}

function writeTracking(tracking) {
  tracking.updatedAt = new Date().toISOString();
  writeJson(trackingPath, tracking);
  fs.writeFileSync(
    trackingJsPath,
    `// Generated by docs/specs/scc-action.mjs.\nwindow.SPEC_COMMAND_CENTER_FEATURE_TRACKING = ${JSON.stringify(tracking, null, 2)};\n`,
  );
}

function diffEntry(before, after) {
  const changes = {};
  const keys = new Set([...Object.keys(before), ...Object.keys(after)]);
  for (const key of keys) {
    if (JSON.stringify(before[key]) !== JSON.stringify(after[key])) {
      changes[key] = { from: before[key] ?? null, to: after[key] ?? null };
    }
  }
  return changes;
}

function appendEvent(event) {
  const line = {
    schemaVersion: eventSchemaVersion,
    eventId: `evt_${Date.now()}_${Math.random().toString(16).slice(2, 8)}`,
    at: new Date().toISOString(),
    ...event,
  };
  fs.appendFileSync(eventsPath, `${JSON.stringify(line)}\n`);
}

function requireFeature(tracking, featureUid) {
  if (!featureUid) throw new Error('Missing --feature <featureUid>');
  const entry = tracking.features[featureUid];
  if (!entry) throw new Error(`Unknown feature UID: ${featureUid}`);
  return entry;
}

function activeAgent(args) {
  return agents.includes(args.agent) ? args.agent : 'codex';
}

function resolveFeatureArg(tracking, args) {
  if (args.feature) return args.feature;
  const active = tracking.activeWork?.[activeAgent(args)];
  if (active?.featureUid) return active.featureUid;
  throw new Error(`Missing --feature <featureUid>; no active Feature for ${activeAgent(args)}`);
}

function assertEnum(field, value, allowed) {
  if (!allowed.includes(value)) {
    throw new Error(`Invalid ${field}: ${value}. Allowed: ${allowed.join(', ')}`);
  }
}

function splitList(value) {
  if (!value) return [];
  return String(value)
    .split(/\n|,/)
    .map((item) => item.trim())
    .filter(Boolean);
}

function updateFeature(tracking, args, mutator) {
  args.feature = resolveFeatureArg(tracking, args);
  const entry = requireFeature(tracking, args.feature);
  const before = structuredClone(entry);
  mutator(entry);
  entry.updatedAt = new Date().toISOString();
  entry.updatedBy = args.actor || defaultActor();
  const changes = diffEntry(before, entry);
  return { entry, changes };
}

function handleAction(action, args, featureList, tracking) {
  if (args.agent && !agents.includes(args.agent)) {
    throw new Error(`Invalid --agent: ${args.agent}. Allowed: ${agents.join(', ')}`);
  }

  if (action === 'sync') {
    writeTracking(tracking);
    appendEvent({
      actor: args.actor || defaultActor(),
      agent: args.agent || null,
      source: args.source || 'cli',
      action: 'tracking_synced',
      featureUid: null,
      summary: args.summary || `Synced tracking store with ${featureList.features.length} features`,
      changes: {},
    });
    return { ok: true, action, features: featureList.features.length };
  }

  if (action === 'audit') {
    return audit(featureList, tracking);
  }

  const { entry, changes } = updateFeature(tracking, args, (target) => {
    if (action === 'start') {
      target.workStatus = 'in_progress';
      target.developer = args.developer || currentGitHubLogin();
      target.branch = args.branch || target.branch || currentBranch();
      tracking.activeWork[activeAgent(args)] = {
        featureUid: target.featureUid,
        title: featureList.features.find((feature) => feature.uid === target.featureUid)?.title || target.featureUid,
        agent: activeAgent(args),
        actor: target.developer,
        branch: target.branch,
        startedAt: new Date().toISOString(),
      };
      return;
    }

    if (action === 'review') {
      if (!args.pr) throw new Error('Missing --pr <number-or-url>');
      target.workStatus = 'in_review';
      target.pr = args.pr;
      target.issue = args.issue || target.issue;
      target.branch = args.branch || target.branch || currentBranch();
      return;
    }

    if (action === 'done') {
      target.workStatus = 'implemented';
      target.branch = args.branch || target.branch || currentBranch();
      target.testStatus = args.tests || target.testStatus;
      target.screenshotStatus = args.screenshots || target.screenshotStatus;
      target.notes = args.notes || target.notes;
      if (tracking.activeWork[activeAgent(args)]?.featureUid === target.featureUid) {
        tracking.activeWork[activeAgent(args)] = null;
      }
      return;
    }

    if (action === 'verify') {
      target.workStatus = 'verified';
      target.testStatus = args.tests || 'passed';
      target.screenshotStatus = args.screenshots || 'passed';
      target.notes = args.notes || target.notes;
      if (tracking.activeWork[activeAgent(args)]?.featureUid === target.featureUid) {
        tracking.activeWork[activeAgent(args)] = null;
      }
      return;
    }

    if (action === 'block') {
      if (!args.reason) throw new Error('Missing --reason <text>');
      target.workStatus = 'blocked';
      target.blockedReason = args.reason;
      target.notes = args.notes || target.notes;
      if (tracking.activeWork[activeAgent(args)]?.featureUid === target.featureUid) {
        tracking.activeWork[activeAgent(args)] = null;
      }
      return;
    }

    if (action === 'unblock') {
      target.workStatus = target.developer && target.developer !== 'Unassigned' ? 'in_progress' : 'not_started';
      target.blockedReason = null;
      target.notes = args.notes || target.notes;
      return;
    }

    if (action === 'set') {
      if (args.status) target.workStatus = args.status;
      if (args.developer) target.developer = args.developer;
      if (args.issue) target.issue = args.issue;
      if (args.pr) target.pr = args.pr;
      if (args.branch) target.branch = args.branch;
      if (args.tests) target.testStatus = args.tests;
      if (args.screenshots) target.screenshotStatus = args.screenshots;
      if (args.notes !== undefined) target.notes = args.notes;
      return;
    }

    if (action === 'plan-set') {
      const now = new Date().toISOString();
      target.workPlan = {
        ...(target.workPlan || defaultEntry(target.featureUid).workPlan),
        status: args.status || target.workPlan?.status || 'draft',
        summary: args.summary || target.workPlan?.summary || '',
        tasks: args.tasks ? splitList(args.tasks) : target.workPlan?.tasks || [],
        affectedFiles: args.files ? splitList(args.files) : target.workPlan?.affectedFiles || [],
        testPlan: args.tests ? splitList(args.tests) : target.workPlan?.testPlan || [],
        risks: args.risks ? splitList(args.risks) : target.workPlan?.risks || [],
        updatedAt: now,
        updatedBy: args.actor || defaultActor(),
      };
      return;
    }

    if (action === 'prompt-log') {
      if (!args.prompt) throw new Error('Missing --prompt <text>');
      const promptHistory = Array.isArray(target.promptHistory) ? target.promptHistory : [];
      promptHistory.unshift({
        promptId: `prompt_${Date.now()}_${Math.random().toString(16).slice(2, 8)}`,
        agent: args.agent || null,
        action: args.promptAction || args['prompt-action'] || 'manual',
        prompt: args.prompt,
        resultSummary: args.result || null,
        createdAt: new Date().toISOString(),
        createdBy: args.actor || defaultActor(),
      });
      target.promptHistory = promptHistory.slice(0, 20);
      return;
    }

    throw new Error(`Unknown action: ${action}`);
  });

  assertEnum('workStatus', entry.workStatus, workStatuses);
  assertEnum('testStatus', entry.testStatus, checkStatuses);
  assertEnum('screenshotStatus', entry.screenshotStatus, checkStatuses);
  assertEnum('workPlan.status', entry.workPlan?.status || 'empty', planStatuses);

  writeTracking(tracking);
  appendEvent({
    actor: args.actor || defaultActor(),
    agent: args.agent || null,
    source: args.source || 'cli',
    action,
    featureUid: entry.featureUid,
    summary: args.summary || `${action} ${entry.featureUid}`,
    changes,
  });

  return { ok: true, action, featureUid: entry.featureUid, changes };
}

function audit(featureList, tracking) {
  const errors = [];
  const warnings = [];
  const featureUids = new Set(featureList.features.map((feature) => feature.uid));

  for (const feature of featureList.features) {
    const entry = tracking.features[feature.uid];
    if (!entry) {
      errors.push(`Missing tracking entry: ${feature.uid}`);
      continue;
    }
    if (!workStatuses.includes(entry.workStatus)) errors.push(`Invalid workStatus for ${feature.uid}: ${entry.workStatus}`);
    if (!checkStatuses.includes(entry.testStatus)) errors.push(`Invalid testStatus for ${feature.uid}: ${entry.testStatus}`);
    if (!checkStatuses.includes(entry.screenshotStatus)) errors.push(`Invalid screenshotStatus for ${feature.uid}: ${entry.screenshotStatus}`);
    if (entry.workStatus === 'in_progress' && entry.developer === 'Unassigned') warnings.push(`In progress without developer: ${feature.uid}`);
    if (entry.workStatus === 'in_review' && !entry.pr) warnings.push(`In review without PR: ${feature.uid}`);
    if (entry.workStatus === 'verified' && (entry.testStatus !== 'passed' || entry.screenshotStatus !== 'passed')) {
      warnings.push(`Verified without passed checks: ${feature.uid}`);
    }
  }

  for (const uid of Object.keys(tracking.features)) {
    if (!featureUids.has(uid)) warnings.push(`Orphan tracking entry: ${uid}`);
  }

  for (const [agent, active] of Object.entries(tracking.activeWork || {})) {
    if (active?.featureUid && !featureUids.has(active.featureUid)) {
      errors.push(`Active work for ${agent} points to unknown Feature UID: ${active.featureUid}`);
    }
  }

  if (fs.existsSync(eventsPath)) {
    fs.readFileSync(eventsPath, 'utf8')
      .split(/\r?\n/)
      .filter(Boolean)
      .forEach((line, index) => {
        try {
          JSON.parse(line);
        } catch {
          errors.push(`Invalid event JSONL at line ${index + 1}`);
        }
      });
  }

  return {
    ok: errors.length === 0,
    features: featureList.features.length,
    trackingEntries: Object.keys(tracking.features).length,
    errors,
    warnings,
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const action = args._[0];
  if (!action) {
    throw new Error('Usage: node docs/specs/scc-action.mjs <sync|audit|start|review|done|verify|block|unblock|set|plan-set|prompt-log> [--feature uid]');
  }

  const featureList = loadFeatureList();
  const tracking = loadTracking(featureList);
  const result = handleAction(action, args, featureList, tracking);
  console.log(JSON.stringify(result, null, 2));
  if (result.ok === false) process.exitCode = 1;
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
